export function SynthwavePepe({ laser = 'neutral' }: SynthwavePepeProps) {
  const laserColor =
    laser === 'green'
      ? 'text-emerald-400'
      : laser === 'red'
      ? 'text-red-400'
      : 'text-retro-cyan neon-cyan'

  let art = neutralArt

  if (laser === 'green') {
    art = greenLaserArt
  } else if (laser === 'red') {
    art = redLaserArt
  }

  return (
    <div className="flex flex-col items-center select-none">
      <pre className={`font-mono text-[5px] leading-[4.2px] tracking-[-0.5px] ${laserColor}`}>
{art}
      </pre>
    </div>
  )
}
